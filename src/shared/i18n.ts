const DICTS: Record<Lang, Record<TKey, string>> = { de, en }

export type Translate = (key: TKey, params?: Record<string, string | number>) => string

export function translator(lang: Lang): Translate {
  const dict = DICTS[lang] ?? de
  return (key, params) => {
    let s = dict[key] ?? de[key] ?? key
    if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v))
    return s
  }
}

/** Wählt anhand der Systemsprache: Deutsch für de-*, sonst Englisch. */
export function langFromLocale(locale: string): Lang {
  return locale.toLowerCase().startsWith('de') ? 'de' : 'en'
}

export function isLang(v: unknown): v is Lang {
  return v === 'de' || v === 'en'
}

/** Gebietsschema für Datums- und Zahlenformatierung */
export function localeOf(lang: Lang): string {
  return lang === 'de' ? 'de-DE' : 'en-GB'
}

